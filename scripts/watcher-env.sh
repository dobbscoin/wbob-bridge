#!/usr/bin/env bash
# Write a minimal env file for watcher N: only the variables watcher/src/config.ts
# reads, copied from the repo .env, with WATCHER_PRIVATE_KEY taken from WATCHER_N_KEY.
# No deployer / executor / emergency / drip key, no HD xpriv, no other watcher's key.
#
#   scripts/watcher-env.sh N            # N = 1..5
#   ENV_FILE=... OUT_DIR=... scripts/watcher-env.sh N   (overrides, for testing)
#
# Output: $OUT_DIR/watcher-N.env (default ~/.config/wbob), mode 0600.
# Values are never printed: only variable names. Lines are copied verbatim, so
# the result parses exactly as the original does under systemd EnvironmentFile=.
# If a name appears more than once in .env, the LAST line wins (as in systemd).
set -euo pipefail

N="${1:-}"
[[ "$N" =~ ^[1-5]$ ]] || { echo "usage: $0 N   (N = 1..5)" >&2; exit 2; }

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${ENV_FILE:-$REPO/.env}"
OUT_DIR="${OUT_DIR:-$HOME/.config/wbob}"
OUT="$OUT_DIR/watcher-$N.env"

# Keep in step with watcher/src/config.ts.
REQUIRED=(DOBBSCOIN_RPC_URL DOBBSCOIN_RPC_USER DOBBSCOIN_RPC_PASS DATABASE_URL
          BRIDGE_CONTROLLER_ADDRESS HD_WALLET_XPUB)
OPTIONAL=(DOBBSCOIN_RPC_TIMEOUT_MS BRIDGE_CONTROLLER_VERSION POLL_INTERVAL_MS
          MIN_CONFIRMATIONS FINAL_CONFIRMATIONS DOBBSCOIN_NETWORK REORG_DEPTH
          WATCHER_CATCHUP_MAX_BLOCKS HD_DERIVATION_PATH DOBBSCOIN_ADDRESS_VERSION
          V2_PRE_CUTOVER_ALLOW V2_MIN_DEPOSIT_HEIGHT)

[[ -r "$ENV_FILE" ]] || { echo "cannot read $ENV_FILE" >&2; exit 1; }

# Last "NAME=..." line for a name (optionally indented), or nothing.
line_for() { grep -E "^[[:space:]]*$1=" "$ENV_FILE" | tail -n 1 || true; }

umask 077
mkdir -p "$OUT_DIR"
chmod 700 "$OUT_DIR"
TMP="$(mktemp "$OUT_DIR/.watcher-$N.env.XXXXXX")"
trap 'rm -f "$TMP"' EXIT

{
  echo "# wBOB watcher $N: minimal env, generated by scripts/watcher-env.sh on $(date -u +%FT%TZ)."
  echo "# Only what watcher/src/config.ts reads. Do not add other secrets here."
} > "$TMP"

written=()
for name in "${REQUIRED[@]}"; do
  l="$(line_for "$name")"
  [[ -n "$l" ]] || { echo "missing required $name in $ENV_FILE" >&2; exit 1; }
  printf '%s\n' "$l" >> "$TMP"; written+=("$name")
done
for name in "${OPTIONAL[@]}"; do
  l="$(line_for "$name")"
  [[ -n "$l" ]] || continue
  printf '%s\n' "$l" >> "$TMP"; written+=("$name")
done

key_line="$(line_for "WATCHER_${N}_KEY")"
[[ -n "$key_line" ]] || { echo "missing WATCHER_${N}_KEY in $ENV_FILE" >&2; exit 1; }
# Rename only the variable; the value (and any quoting) is copied untouched.
printf '%s\n' "$key_line" | sed -E "s/^[[:space:]]*WATCHER_${N}_KEY=/WATCHER_PRIVATE_KEY=/" >> "$TMP"
written+=("WATCHER_PRIVATE_KEY(<-WATCHER_${N}_KEY)")

chmod 600 "$TMP"
mv -f "$TMP" "$OUT"
trap - EXIT
echo "wrote $OUT (0600): ${written[*]}"
if grep -q '^[[:space:]]*V2_PRE_CUTOVER_ALLOW=' "$OUT"; then
  echo "note: V2_PRE_CUTOVER_ALLOW is a file path; on another box that file must be copied to the same path."
fi
